# operators ka mtlb jaise plus, minus, multiply, divide, etc. 
# ye operators humein mathematical operations perform karne mein madad karte hain.
# Python mein kuch common operators hain:
# 1. Arithmetic Operators: +, -, *, /, %, **, //
print(5 + 3)  # isse simple add hoga
print(5 - 3)  # isse simple subtract hoga
print(5 * 3)  # isse simple multiply hoga
print(5 ** 3) # iska mtlb 5 ki power me 3 h
print(5 / 3)  # iska mtlb divide simple
print(5 // 3) # isme divide krne pr jo aayega usme point k bad vala hta denge
print(5 % 3)  # isme divide krne pr jo remainder aayega wo likhega
# 2. Comparison Operators: ==, !=, >, <, >=, <=
print(5 == 3)  # isse check karega ki 5 aur 3 barabar hain ya nahi
print(5 != 3)  # isse check karega ki 5 aur 3 barabar nahi hain ya nahi
print(5 > 3)   # isse check karega ki 5 bada hai ya nahi
print(5 < 3)   # isse check karega ki 5 chhota hai ya nahi
print(5 >= 3)  # isse check karega ki 5 bada ya barabar hai ya nahi
print(5 <= 3)  # isse check karega ki 5 chhota ya barabar hai ya nahi
# 3. Logical Operators: and, or, not
print(True and False)  # isse check karega ki dono true hain ya nahi
print(True or False)   # isse check karega ki kam se kam ek true hai ya nahi
print(not True)        # isse check karega ki true nahi hai ya nahi
print(not False)       # isse check karega ki false nahi hai ya nahi