# escape sequence character

# /n is used to print the next line
print("I am a good boy \n i am a real boy\n")


# \t is used to print a tab space
print("I am a good boy \t i am a real boy\n")


# \\ is used to print a backslash
print("I am a good boy \\ i am a real boy\n")


# \' is used to print a single quote
print('I am a good \' boy \' i am a real boy\n')


# \" is used to print a double quote
print("I am a \" good boy \" i am a real boy\n")


